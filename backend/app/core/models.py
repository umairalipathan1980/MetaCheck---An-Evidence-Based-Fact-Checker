class SearchStatus(BaseModel):
    """Status of a search operation - tracks success, failure, or no results"""
    tool: Literal["web_search", "wikipedia", "google_fact_check"]
    status: Literal["success", "error", "no_api_key", "no_results"]
    results_count: int = 0
    error_message: Optional[str] = None
    timestamp: datetime = Field(default_factory=datetime.now)


class SearchStatusSummary(BaseModel):
    """Summary of all search statuses for a verification"""
    web_search: Optional[SearchStatus] = None
    wikipedia: Optional[SearchStatus] = None
    google_fact_check: Optional[SearchStatus] = None

    @property
    def any_failures(self) -> bool:
        """Check if any search failed"""
        statuses = [self.web_search, self.wikipedia, self.google_fact_check]
        return any(s and s.status in ("error", "no_api_key") for s in statuses)

    @property
    def failed_searches(self) -> List[str]:
        """Get list of failed search tools"""
        failed = []
        for name, status in [
            ("web_search", self.web_search),
            ("wikipedia", self.wikipedia),
            ("google_fact_check", self.google_fact_check)
        ]:
            if status and status.status in ("error", "no_api_key"):
                failed.append(name)
        return failed


class EvidenceBundle(BaseModel):
    """Structured evidence payload returned by tools"""
    evidence: List[Evidence]
    search_status: Optional[SearchStatusSummary] = None


