class VerificationResult(BaseModel):
    """Result of verifying a single claim - Enhanced with full metacognitive detail"""
    claim: str
    verdict: Literal["SUPPORTED", "REFUTED", "INSUFFICIENT_INFORMATION", "CONFLICTING_EVIDENCE"]
    confidence: float = Field(ge=0.0, le=1.0)
    justification: str
    key_sources: List[str]  # Format: "Source Name [URL]"
    evidence_list: List[Evidence] = []
    metacognitive_steps: List[MetacognitiveStep] = []

    # Enhanced metacognitive details for educational transparency
    metacognitive_detail: Optional[MetacognitiveDetail] = None


class FinalAssessment(BaseModel):
    """Final assessment of all claims"""
    input_text: str
    total_claims: int
    claim_results: List[VerificationResult]
    overall_credibility: str
    mode: Literal["basic", "comprehensive"] = "basic"
    generated_at: datetime = Field(default_factory=datetime.now)

    # Search status tracking - shows which searches succeeded/failed
    search_status: Optional[SearchStatusSummary] = None


class OrchestratorOutput(BaseModel):
    """Structured output from the orchestrator with all verified claims"""
    claim_results: List[VerificationResult]
    summary: str = ""


class ComparisonAnalysis(BaseModel):
    """Analysis comparing student claims with AI-extracted claims"""
    overall_summary: str  # High-level summary of agreement/disagreement
    strengths: List[str]  # What the student did well
    areas_for_improvement: List[str]  # What could be improved
    key_insights: List[str]  # Important insights from the comparison
    claim_by_claim_feedback: List[str]  # Detailed feedback for each claim pair
    learning_opportunities: List[str]  # Specific learning suggestions
    encouragement: str  # Positive, encouraging closing message


