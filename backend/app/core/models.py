"""
MetaCheck Data Models

All Pydantic models used throughout the MetaCheck system.
"""

from datetime import datetime
from typing import List, Optional, Literal, Dict
from pydantic import BaseModel, Field


# ============================================================================
# CORE DATA MODELS
# ============================================================================

class Claim(BaseModel):
    """A single factual claim extracted from text"""
    text: str
    worthiness_score: float = Field(
        ge=0.0,
        le=1.0,
        default=0.8,
        description=(
            "Priority score (0.0-1.0) for verification based on: "
            "1) SPECIFICITY: concrete facts/numbers/dates > vague statements; "
            "2) VERIFIABILITY: requires external sources > common knowledge; "
            "3) IMPACT: potential harm if false > low-stakes information. "
            "Scoring guide: "
            "0.8-1.0 = High priority (specific statistics, recent events, controversial claims, health/safety info); "
            "0.5-0.7 = Medium priority (verifiable but lower stakes, historical facts, attributable quotes); "
            "0.0-0.4 = Low priority (well-known facts, definitions, subjective opinions, trivial details). "
            "Consider: Would this claim mislead readers if unchecked? Does it contain checkable details?"
        ),
    )

    extracted_at: datetime = Field(default_factory=datetime.now)


class ClaimList(BaseModel):
    """List of extracted claims"""
    claims: List[Claim]
    extraction_method: str = "AI claim extractor"


class Evidence(BaseModel):
    """A single piece of evidence from a source"""
    source_name: str
    source_type: Literal["fact_check", "wikipedia", "web_search"]
    url: str
    snippet: str
    relevance_score: float = Field(ge=0.0, le=1.0, default=0.7)
    credibility_score: float = Field(ge=0.0, le=1.0, default=0.7)
    stance: Optional[Literal["supports", "refutes", "neutral", "unclear"]] = None


class MetacognitiveStep(BaseModel):
    """A step in the metacognitive reasoning process"""
    timestamp: datetime = Field(default_factory=datetime.now)
    agent: str
    action: str
    reasoning: str
    confidence: Optional[float] = None


